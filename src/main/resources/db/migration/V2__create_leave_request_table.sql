CREATE TABLE leave_request (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id    BIGINT       NOT NULL,
    start_date     DATE         NOT NULL,
    end_date       DATE         NOT NULL,
    requested_days NUMERIC(5, 2) NOT NULL,
    status         VARCHAR(20)  NOT NULL,
    reason         VARCHAR(500),
    review_comment VARCHAR(500),
    created_at     TIMESTAMPTZ  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    reviewed_at    TIMESTAMPTZ,
    version        BIGINT       NOT NULL,
    CONSTRAINT fk_leave_request_employee FOREIGN KEY (employee_id) REFERENCES employee (id),
    CONSTRAINT ck_leave_request_date_range CHECK (start_date <= end_date),
    CONSTRAINT ck_leave_request_days_positive CHECK (requested_days > 0),
    CONSTRAINT ck_leave_request_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'))
);
