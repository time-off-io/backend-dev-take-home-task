CREATE TABLE employee (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name             VARCHAR(100) NOT NULL,
    last_name              VARCHAR(100) NOT NULL,
    email                  VARCHAR(255) NOT NULL,
    annual_leave_allowance INTEGER      NOT NULL,
    remaining_leave_days   NUMERIC(5, 2) NOT NULL,
    active                 BOOLEAN      NOT NULL,
    created_at             TIMESTAMPTZ  NOT NULL,
    updated_at             TIMESTAMPTZ  NOT NULL,
    version                BIGINT       NOT NULL,
    CONSTRAINT uq_employee_email UNIQUE (email),
    CONSTRAINT ck_employee_allowance_positive CHECK (annual_leave_allowance > 0),
    CONSTRAINT ck_employee_remaining_non_negative CHECK (remaining_leave_days >= 0)
);
